using System;

class Program
{
    enum УровеньВорчливости
    {
        Низкий,
        Средний,
        Высокий,
        Экстремальный
    }
    struct Дед
    {
        public string Имя;
        public УровеньВорчливости Ворчливость;
        public string[] ФразыДляВорчания;
        public int КоличествоСиняков;
        public Дед(string имя, УровеньВорчливости ворчливость, string[] фразы)
        {
            Имя = имя;
            Ворчливость = ворчливость;
            ФразыДляВорчания = фразы;
            КоличествоСиняков = 0; 
        }
        public int ПроверитьЛексику(ref Дед дед, params string[] матерныеСлова)
        {
            int новыеСиняки = 0;

            foreach (string фраза in дед.ФразыДляВорчания)
            {
          
                foreach (string мат in матерныеСлова)
                {
                    if (фраза.Contains(мат, StringComparison.OrdinalIgnoreCase))
                    {
                        новыеСиняки++;
                    }
                }
            }
            дед.КоличествоСиняков += новыеСиняки;
            return новыеСиняки;
        }
    }

    static void Main()
    {
        Дед[] деды = new Дед[5];

        деды[0] = new Дед("Иваныч", УровеньВорчливости.Низкий, new string[]
            { "Раньше было лучше", "Опять чай подорожал" });

        деды[1] = new Дед("Петрович", УровеньВорчливости.Средний, new string[]
            { "Проститутки у подъезда!", "Гады, весь двор заставили машинами!", "Цены ужас!" });

        деды[2] = new Дед("Михалыч", УровеньВорчливости.Высокий, new string[]
            { "Эй ты, козел криворукий!", "Да пошел ты нафиг!", "Опять нажрался, скотина", "Наркоманы!" }); 

        деды[3] = new Дед("Савельич", УровеньВорчливости.Экстремальный, new string[]
            { "Черти полосатые!", "Блин, опять деталь потерял" });

        деды[4] = new Дед("Степаныч", УровеньВорчливости.Высокий, new string[]
            { "Вот же гадство какое!", "Уроды сломали лавочку", "Политики хреновы", "Тунеядцы!", "Разворовали всё!" });

        string[] черныйСписок = { "гад", "козел", "скотина", "урод" };


        for (int i = 0; i < деды.Length; i++)
        {
            int полученоФингалов = деды[i].ПроверитьЛексику(ref деды[i], черныйСписок);

            Console.WriteLine($"Дед: {деды[i].Имя} ({деды[i].Ворчливость} уровень ворчливости)");
            Console.WriteLine($"Фраз в запасе: {деды[i].ФразыДляВорчания.Length}");
            Console.WriteLine($"Получил фингалов за этот раз: {полученоФингалов}");
            Console.WriteLine($"Всего синяков от бабки: {деды[i].КоличествоСиняков}");
            Console.WriteLine(new string('-', 40));
        }
    }
}
